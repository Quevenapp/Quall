def write(relative, data):
    path = ROOT / relative
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(data.encode("utf-8") if isinstance(data, str) else data)
    OUTPUTS.append(relative)


def chunk(kind, data):
    return struct.pack(">I", len(data)) + kind + data + struct.pack(">I", binascii.crc32(kind + data) & 0xffffffff)


def rgba(side, transparent=False):
    """A four-cell grid, with integer coordinates and no copied brand geometry."""
    pixels = bytearray()
    for y in range(side):
        pixels.append(0)  # PNG filter: none
        for x in range(side):
            u, v = (x + 0.5) / side, (y + 0.5) / side
            outside = transparent and not (0.08 <= u <= 0.92 and 0.08 <= v <= 0.92)
            color = (36, 51, 67, 0 if outside else 255)
            for left, top, right, bottom, rgb in (
                (0.25, 0.25, 0.47, 0.47, (236, 243, 247)),
                (0.53, 0.25, 0.75, 0.47, (84, 196, 184)),
                (0.25, 0.53, 0.47, 0.75, (84, 196, 184)),
                (0.53, 0.53, 0.75, 0.75, (236, 243, 247)),
            ):
                if left <= u <= right and top <= v <= bottom:
                    color = rgb + (255,)
            pixels.extend(color)
    return bytes(pixels)


def png(side, transparent=False, rgb=False):
    raw = rgba(side, transparent)
    if rgb:
        rows = bytearray()
        stride = 1 + side * 4
        for y in range(side):
            rows.append(0)
            row = raw[y * stride + 1:(y + 1) * stride]
            for x in range(side):
                rows.extend(row[x * 4:x * 4 + 3])
        raw = bytes(rows)
    header = struct.pack(">IIBBBBB", side, side, 8, 2 if rgb else 6, 0, 0, 0)
    return b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", header) + chunk(b"IDAT", zlib.compress(raw, 9)) + chunk(b"IEND", b"")


def ico():
    images = [png(size, transparent=True) for size in WINDOWS_SIZES]
    offset = 6 + 16 * len(images)
    directory = bytearray(struct.pack("<HHH", 0, 1, len(images)))
    for size, image in zip(WINDOWS_SIZES, images):
        directory.extend(struct.pack("<BBBBHHII", size % 256, size % 256, 0, 0, 1, 32, len(image), offset))
        offset += len(image)
    return bytes(directory) + b"".join(images)


def icns():
    entries = []
    for kind, size in ((b"icp4", 16), (b"icp5", 32), (b"icp6", 64), (b"ic07", 128),
                       (b"ic08", 256), (b"ic09", 512), (b"ic10", 1024)):
        image = png(size, transparent=True)
        entries.append(kind + struct.pack(">I", len(image) + 8) + image)
    body = b"".join(entries)
    return b"icns" + struct.pack(">I", len(body) + 8) + body


def polygon(cx, cy, radius, count=12):
    points = [(cx + radius * math.cos(2 * math.pi * n / count),
               cy + radius * math.sin(2 * math.pi * n / count)) for n in range(count)]
    return "M" + " L".join(f"{x:.2f},{y:.2f}" for x, y in points) + " Z"


