def vector(path, viewport=24, side=24, stroke=True, color="#FF000000"):
    attributes = 'android:fillColor="#00000000" android:strokeColor="' + color + '" android:strokeWidth="1.7" android:strokeLineCap="round" android:strokeLineJoin="round"' if stroke else 'android:fillColor="' + color + '"'
    return XML_HEAD + XML_NOTICE + f'<vector {ANDROID_NS} android:width="{side}dp" android:height="{side}dp" android:viewportWidth="{viewport}" android:viewportHeight="{viewport}">\n    <path {attributes} android:pathData="{path}" />\n</vector>\n'


